    private void btnDeleteEntryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteEntryActionPerformed
            SessionManager.updateLastActivity();
            int selectedIndex = lstSites.getSelectedIndex();

            if (selectedIndex < 0 || filteredEntries == null || selectedIndex >= filteredEntries.size()) {
                JOptionPane.showMessageDialog(this, "Lütfen silmek için bir kayıt seçin!");
                return;
            }

            VaultEntry selectedEntry = filteredEntries.get(selectedIndex);
            User currentUser = SessionManager.getCurrentUser();

            VaultService vaultService = new VaultService();
            boolean result = vaultService.deleteVaultEntry(currentUser, selectedEntry.getId());

            if (result) {
                JOptionPane.showMessageDialog(this, "Kayıt silindi!");
                loadEntries();
            } else {
                JOptionPane.showMessageDialog(this, "Silme işlemi başarısız!");
            }
    }//GEN-LAST:event_btnDeleteEntryActionPerformed

    private void btnEditEntryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditEntryActionPerformed
            SessionManager.updateLastActivity();
            int selectedIndex = lstSites.getSelectedIndex();

            if (selectedIndex < 0 || filteredEntries == null || selectedIndex >= filteredEntries.size()) {
                JOptionPane.showMessageDialog(this, "Lütfen düzenlemek için bir kayıt seçin!");
                return;
            }

            VaultEntry selectedEntry = filteredEntries.get(selectedIndex);

            EditEntryDialog dialog = new EditEntryDialog(this, true, selectedEntry);
            dialog.setVisible(true);

            loadEntries();
    }//GEN-LAST:event_btnEditEntryActionPerformed

