        private void startSessionTimer() {
            sessionTimer = new javax.swing.Timer(10000, e -> {
                if (SessionManager.isSessionExpired() && !SessionManager.isManuallyLoggedOut()) {
                    SessionManager.logout();
                    JOptionPane.showMessageDialog(this, "Oturum zaman aşımına uğradı. Lütfen yeniden giriş yapın.");

                    LoginForm loginForm = new LoginForm();
                    loginForm.setVisible(true);
                    this.dispose();
                }
            });

            sessionTimer.start();
        }

    
    private void loadEntries() {
        try {
            User currentUser = SessionManager.getCurrentUser();

            if (currentUser == null) {
                return;
            }

            VaultService vaultService = new VaultService();
            currentEntries = vaultService.getDecryptedEntries(currentUser);
            filteredEntries = new java.util.ArrayList<>(currentEntries);

            refreshSiteList();

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
        private void filterEntries() {
            String searchText = txtSearch.getText().trim().toLowerCase();

            filteredEntries = new java.util.ArrayList<>();

            if (currentEntries == null) {
                return;
            }

            for (VaultEntry entry : currentEntries) {
                if (entry.getSiteName().toLowerCase().contains(searchText)) {
                    filteredEntries.add(entry);
                }
            }

            refreshSiteList();
        }
    
        private void refreshSiteList() {
            javax.swing.DefaultListModel<String> listModel = new javax.swing.DefaultListModel<>();

            for (VaultEntry entry : filteredEntries) {
                listModel.addElement(entry.getSiteName());
            }

            lstSites.setModel(listModel);
            clearDetailFields();
        }
    
    private void showSelectedEntryDetails() {
        int selectedIndex = lstSites.getSelectedIndex();

        if (selectedIndex >= 0 && filteredEntries != null && selectedIndex < filteredEntries.size()) {
            eduvault.model.VaultEntry entry = filteredEntries.get(selectedIndex);

            txtDetailSiteName.setText(entry.getSiteName());
            txtDetailUrl.setText(entry.getSiteUrl());
            txtDetailUsername.setText(entry.getAccountUsername());
            txtDetailPassword.setText(entry.getDecryptedPassword());
            txtDetailNote.setText(entry.getNote());
        }
    }
    private void clearDetailFields() {
        txtDetailSiteName.setText("");
        txtDetailUrl.setText("");
        txtDetailUsername.setText("");
        txtDetailPassword.setText("");
        txtDetailNote.setText("");
    }
    
    

