    private void btnGeneratePasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGeneratePasswordActionPerformed
        PasswordGeneratorService generator = new PasswordGeneratorService();

        int length = (Integer) spnPasswordLength.getValue();

        String generatedPassword = generator.generatePassword(length, true, true, true, true);

        txtGeneratedPassword.setText(generatedPassword);
    }//GEN-LAST:event_btnGeneratePasswordActionPerformed

    private void btnCopyGeneratedPasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCopyGeneratedPasswordActionPerformed
        String generatedPassword = txtGeneratedPassword.getText();

        if (generatedPassword == null || generatedPassword.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Önce parola üretin!");
        return;
        }

        java.awt.datatransfer.StringSelection selection =
        new java.awt.datatransfer.StringSelection(generatedPassword);

        java.awt.Toolkit.getDefaultToolkit()
        .getSystemClipboard()
        .setContents(selection, null);

        JOptionPane.showMessageDialog(this, "Parola panoya kopyalandı!");
    }//GEN-LAST:event_btnCopyGeneratedPasswordActionPerformed

