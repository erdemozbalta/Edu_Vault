    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String username = txtUsername.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();
        String password = new String(txtPassword.getPassword());
        String repeatPassword = new String(txtRepeatPassword.getPassword());

        if (!password.equals(repeatPassword)) {
            JOptionPane.showMessageDialog(this, "Parolalar eşleşmiyor!");
            return;
        }

        AuthService authService = new AuthService();

        String usernameMessage = authService.getUsernameValidationMessage(username);
        if (!usernameMessage.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Kullanıcı adı geçersiz:\n" + usernameMessage,
                    "Geçersiz Kullanıcı Adı",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        String emailMessage = authService.getEmailValidationMessage(email);
        if (!emailMessage.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "E-posta geçersiz:\n" + emailMessage,
                    "Geçersiz E-posta",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        String phoneMessage = authService.getPhoneValidationMessage(phone);
        if (!phoneMessage.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Telefon numarası geçersiz:\n" + phoneMessage,
                    "Geçersiz Telefon Numarası",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        String passwordMessage = authService.getPasswordValidationMessage(password);
        if (!passwordMessage.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Parola yeterince güçlü değil:\n" + passwordMessage,
                    "Geçersiz Parola",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        RegisterResult result = authService.register(username, email, phone, password);

        if (result.isSuccess()) {
            String formattedWords = formatRecoveryWords(result.getRecoveryPhrase());

            JOptionPane.showMessageDialog(this,
                    "Kayıt başarılı!\n\nKurtarma Kelimeleri:\n\n"
                    + formattedWords
                    + "\nBu kelimeleri sırayla ve eksiksiz şekilde güvenli bir yerde saklayın.   \n"
                    + "\nAna şifrenizi unutmanız halinde parola sıfırlama için istenecektir.   \n"
                    + "\nBu kelimeleri not ediniz bir daha gösterilmeyecektir.   \n");

            LoginForm loginForm = new LoginForm();
            loginForm.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, result.getMessage());
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

