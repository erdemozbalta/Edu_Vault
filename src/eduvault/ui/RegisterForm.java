    private String formatRecoveryWords(String recoveryPhrase) {
        String[] words = recoveryPhrase.trim().split("\\s+");
        StringBuilder sb = new StringBuilder();

        for (int i = 0; i < words.length; i++) {
            sb.append(i + 1).append(". ").append(words[i]).append("\n");
        }

        return sb.toString();
    }

